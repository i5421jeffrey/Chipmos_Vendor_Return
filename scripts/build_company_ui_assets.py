"""Reproduce original SPMS CSS/logo locally, without copying cloud JS or passwords."""
import base64
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    source = ROOT / 'docs/repairs/index.html'
    logo = ROOT / 'docs/repairs/ghost-logo.png'
    css = source.read_text(encoding='utf-8').split('<style>', 1)[1].split('</style>', 1)[0].strip()
    if 'url(' in css.lower() or '@import' in css.lower():
        raise ValueError('Review CSS resource references before packaging')
    original_css = '/* Original SPMS CSS from docs/repairs/index.html; generated by scripts/build_company_ui_assets.py. */\n' + css + '\n'
    branding = json.dumps({'source': 'docs/repairs/ghost-logo.png', 'sha256': hashlib.sha256(logo.read_bytes()).hexdigest(),
                           'content_base64': base64.b64encode(logo.read_bytes()).decode('ascii')}, indent=2) + '\n'
    return {'original.css': original_css, 'branding.json': branding}


if __name__ == '__main__':
    for name, content in build().items():
        path = ROOT / 'company/web' / name
        path.write_bytes(content.encode('utf-8'))
        print(path)
